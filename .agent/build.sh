#!/usr/bin/env bash
# .agent/rules/NN_name.md をファイル名順に結合して、リポジトリ直下の AGENTS.md / CLAUDE.md を生成するスクリプト
# 人格や汎用的なルールはマシンのグローバル設定で管理するため、ここにはリポジトリ固有のルールだけを置く
set -euo pipefail

# どのディレクトリから実行してもリポジトリ直下で動くように、スクリプトの場所から移動する
cd "$(dirname "$(readlink -f "$0")")/.."

RULES_DIR=".agent/rules"
OUTPUT_FILES=("AGENTS.md" "CLAUDE.md")

shopt -s nullglob
rules=("$RULES_DIR"/[0-9][0-9]_*.md)
if [[ ${#rules[@]} -eq 0 ]]; then
  echo "No rule files found in $RULES_DIR" >&2
  exit 1
fi

# 途中で失敗しても書きかけのファイルが残らないように、一時ファイルに書いてから置き換える
tmp="$(mktemp "AGENTS.md.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
# mktemp は 0600 で作成するため、通常のファイルと同じ権限にそろえる
chmod 644 "$tmp"

{
  echo "<!-- Generated by .agent/build.sh from .agent/rules/*.md. Edit the rule files, not this file. -->"
  echo
  for i in "${!rules[@]}"; do
    # ルールファイルの間は空行 1 行で区切る
    [[ $i -gt 0 ]] && echo
    # 末尾の空行を取り除き、区切りの空行の数をそろえる
    sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "${rules[$i]}"
  done
} > "$tmp"

for output_file in "${OUTPUT_FILES[@]}"; do
  cp "$tmp" "$output_file"
done

echo "Generated ${OUTPUT_FILES[*]} from ${#rules[@]} rule files"
